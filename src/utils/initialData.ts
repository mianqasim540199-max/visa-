export const CURRENCY_RATES = {
  PKR: 1,
  USD: 0.0036, // 1 USD ~ 278 PKR
  SAR: 0.0135, // 1 SAR ~ 74 PKR
  AED: 0.0132, // 1 AED ~ 75.8 PKR
};

export function formatCurrency(amount: number, currency: keyof typeof CURRENCY_RATES = 'PKR'): string {
  const converted = amount * CURRENCY_RATES[currency];
  if (currency === 'PKR') {
    return `PKR ${Math.round(converted).toLocaleString('en-US')}`;
  }
  return `${currency} ${converted.toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}
